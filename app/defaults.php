/** Units as delivered (from the building's unit schedule and the model sheets). */
function default_units(): array
{
    $models = [
        'A' => [1, 4, 5, 6, 7, 8, 9, 12, 13, 14, 15, 16, 17, 20, 21, 22, 23, 24, 25, 28, 29, 30, 31, 32],
        'B' => [2, 3, 10, 11, 18, 19, 26, 27, 34, 35],
        'C' => [33, 36],
    ];
    $modelOf = function (int $n) use ($models): string {
        foreach ($models as $k => $list) if (in_array($n, $list, true)) return $k;
        return '';
    };
    $typical = [[94.05, 1, 1], [92.15, 1, 1], [92.15, 1, 1], [94.05, 1, 1], [92.07, 1, 1], [85.92, 0, 1], [85.92, 0, 1], [92.07, 1, 1]];
    $annex = [[86.31, 1, 0, 94.05], [85.92, 0, 0, null], [85.92, 0, 0, null], [85.92, 1, 0, 94.05]];
    $out = [];
    for ($f = 1; $f <= 4; $f++) {
        foreach ($typical as $i => [$area, $laundry, $terrace]) {
            $no = ($f - 1) * 8 + $i + 1;
            $out[] = ['no' => $no, 'floor' => $f, 'area' => $area, 'model' => $modelOf($no), 'laundry' => $laundry, 'terrace' => $terrace, 'roof' => null];
        }
    }
    foreach ($annex as $i => [$area, $laundry, $terrace, $roof]) {
        $no = 33 + $i;
        $out[] = ['no' => $no, 'floor' => 5, 'area' => $area, 'model' => $modelOf($no), 'laundry' => $laundry, 'terrace' => $terrace, 'roof' => $roof];
    }
    return $out;
}
